CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION check_admin_exists()
RETURNS TRIGGER AS $$
BEGIN
  IF (TG_OP = 'DELETE' OR (TG_OP = 'UPDATE' AND NEW.cargo != 'administrador')) THEN
    IF OLD.cargo = 'administrador' AND (
      SELECT COUNT(*) FROM public."AUTORIZAÇÃO"
      WHERE cargo = 'administrador'
        AND id_empresa = OLD.id_empresa
        AND id != OLD.id
    ) = 0 THEN
      RAISE EXCEPTION 'Não é possível remover o último administrador da empresa.';
    END IF;
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;


