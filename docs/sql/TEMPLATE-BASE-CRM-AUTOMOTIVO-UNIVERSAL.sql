-- ============================================================
-- PERMISSÕES E RLS — liberação para chamadas do n8n
-- Executa por último, depois de todas as tabelas criadas
-- ============================================================

DO $$
DECLARE
    r RECORD;
BEGIN
    -- 1. Concede permissões em todas as tabelas atuais para o n8n
    GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO authenticated;
    GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO service_role;
    GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO postgres;
    -- 2. Concede permissões em todas as sequências atuais (IDs automáticos)
    GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO authenticated;
    GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO service_role;
    GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO postgres;
    -- 3. Desativa o RLS de absolutamente todas as tabelas para ficarem "UNRESTRICTED"
    FOR r IN (SELECT tablename FROM pg_tables WHERE schemaname = 'public') LOOP
        EXECUTE 'ALTER TABLE public.' || quote_ident(r.tablename) || ' DISABLE ROW LEVEL SECURITY;';
    END LOOP;
END $$;

-- 4. Garante que qualquer NOVA tabela criada no futuro já nasça com permissão total
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON TABLES TO authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON TABLES TO service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON TABLES TO postgres;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON SEQUENCES TO authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON SEQUENCES TO service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON SEQUENCES TO postgres;


